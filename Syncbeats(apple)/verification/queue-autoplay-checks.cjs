// Real room state only: no database, network provider, or production account.
require('../../dev/syncbeats-server/node_modules/ts-node').register({transpileOnly:true,compilerOptions:{module:'CommonJS',moduleResolution:'Node',ignoreDeprecations:'6.0'}});
const assert = require('node:assert/strict');
const {Room} = require('../../dev/syncbeats-server/src/core/Room.ts');
const {RoomQueue} = require('../../dev/syncbeats-server/src/core/RoomQueue.ts');
const room = new Room('123456');
room.addParticipant({socketId:'fixture',displayName:'Fixture',isReady:true});
const a = room.addTracks([{trackUrl:'https://example.test/a.wav',title:'A',durationSec:3}], 'fixture').added[0];
const b = room.addTracks([{trackUrl:'https://example.test/b.wav',title:'B',durationSec:3}], 'fixture').added[0];
const c = room.addTracks([{trackUrl:'https://example.test/c.wav',title:'C',durationSec:3}], 'fixture').added[0];
room.setParticipantReady('fixture', true);
room.setCurrentItem(a.id,true);
room.setParticipantReady('fixture', true);
assert.equal(room.snapshot().autoplay,true);
const first = room.snapshot().playbackInstanceId;
assert.ok(first);
room.setAutoplay(false);
room.handleTrackEnded(a.trackUrl,first);
assert.equal(room.snapshot().isPlaying,false);
assert.equal(room.snapshot().trackUrl,a.trackUrl);
assert.equal(room.snapshot().nextTrack.id,b.id);
assert.equal(room.handleTrackEnded(a.trackUrl,first),null);
room.setAutoplay(true);
assert.equal(room.handleTrackEnded(a.trackUrl),null);
assert.equal(room.snapshot().trackUrl,a.trackUrl);
room.setAutoplay(false);
room.nextTrack(true);
room.setParticipantReady('fixture', true);
assert.equal(room.snapshot().trackUrl,b.trackUrl);
assert.equal(room.snapshot().autoplay,false);
assert.equal(RoomQueue.fromJSON(room.getQueueState()).autoplay,false);
const legacy = room.getQueueState(); delete legacy.autoplay;
assert.equal(RoomQueue.fromJSON(legacy).autoplay,true);
room.setAutoplay(true);
const second = room.snapshot().playbackInstanceId;
assert.ok(second);
room.handleTrackEnded(b.trackUrl,second);
assert.equal(room.snapshot().trackUrl,c.trackUrl);
assert.equal(room.handleTrackEnded(b.trackUrl,second),null);
console.log('PASS: default Autoplay, stop and retain queue, manual Next, persistence, legacy defaults, continue once');
room.pause('fixture');
room.removeAllListeners();
